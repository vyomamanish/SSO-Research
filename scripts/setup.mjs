#!/usr/bin/env node
// Generates every secret the demo needs. Safe to re-run: existing files are kept,
// because changing PG_PASS or the client secrets would break a running Authentik.
import { randomBytes } from "node:crypto";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const secret = (bytes = 36) => randomBytes(bytes).toString("base64url");

const parseEnv = (text) =>
  Object.fromEntries(
    text
      .split(/\r?\n/)
      .filter((line) => line && !line.startsWith("#") && line.includes("="))
      .map((line) => [line.slice(0, line.indexOf("=")), line.slice(line.indexOf("=") + 1)]),
  );

function writeIfMissing(relativePath, contents) {
  const path = join(root, relativePath);
  if (existsSync(path)) {
    console.log(`kept     ${relativePath}`);
    return;
  }
  writeFileSync(path, contents, { mode: 0o600 });
  console.log(`created  ${relativePath}`);
}

writeIfMissing(
  ".env",
  `# Generated by scripts/setup.mjs. Do not commit.
PG_PASS=${secret()}
AUTHENTIK_SECRET_KEY=${secret(60)}
AUTHENTIK_ERROR_REPORTING__ENABLED=false
OTT_CLIENT_SECRET=${secret()}
DSG_CLIENT_SECRET=${secret()}
DEMO_ADMIN_PASSWORD=${secret(12)}
DEMO_STAFF_PASSWORD=${secret(12)}
`,
);

const env = parseEnv(readFileSync(join(root, ".env"), "utf8"));

const appEnv = (slug, port, otherPort, clientSecret, extra = "") =>
  `# Generated by scripts/setup.mjs. Do not commit.
AUTH_URL=http://localhost:${port}
AUTH_SECRET=${secret()}
AUTH_TRUST_HOST=true
AUTH_AUTHENTIK_ID=${slug}
AUTH_AUTHENTIK_SECRET=${clientSecret}
AUTH_AUTHENTIK_ISSUER=http://localhost:9000/application/o/${slug}/
OTHER_APP_URL=http://localhost:${otherPort}
${extra}`;

writeIfMissing(
  "app-a/.env.local",
  appEnv("ott-demo", 3001, 3002, env.OTT_CLIENT_SECRET, "API_URL=http://localhost:4000\n"),
);
writeIfMissing("app-b/.env.local", appEnv("dsg-demo", 3002, 3001, env.DSG_CLIENT_SECRET));

console.log(`
Demo logins (also stored in .env):
  admin  vyoma.admin / ${env.DEMO_ADMIN_PASSWORD}
  staff  vyoma.staff / ${env.DEMO_STAFF_PASSWORD}`);
