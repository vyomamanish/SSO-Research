#!/usr/bin/env node
// Generates every secret the demo needs. Safe to re-run: values that already
// exist are kept, because changing PG_PASS or a client secret would break a
// running Authentik. Only missing keys are added.
import { randomBytes } from "node:crypto";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const secret = (bytes = 36) => randomBytes(bytes).toString("base64url");
const hex = (bytes = 32) => randomBytes(bytes).toString("hex");

function readEnv(relativePath) {
  const path = join(root, relativePath);
  if (!existsSync(path)) return {};
  return Object.fromEntries(
    readFileSync(path, "utf8")
      .split(/\r?\n/)
      .filter((line) => line && !line.startsWith("#") && line.includes("="))
      .map((line) => [line.slice(0, line.indexOf("=")), line.slice(line.indexOf("=") + 1)]),
  );
}

/** Writes `wanted` into the file, keeping any value already there. */
function mergeEnv(relativePath, wanted) {
  const existing = readEnv(relativePath);
  const merged = { ...wanted, ...existing };
  // Keys this version no longer uses are dropped.
  const lines = Object.keys(wanted).map((key) => `${key}=${merged[key]}`);
  const added = Object.keys(wanted).filter((key) => !(key in existing));
  writeFileSync(
    join(root, relativePath),
    `# Generated by scripts/setup.mjs. Do not commit.\n${lines.join("\n")}\n`,
    { mode: 0o600 },
  );
  console.log(`${added.length ? "updated" : "kept   "}  ${relativePath}${added.length ? ` (+${added.length})` : ""}`);
  return merged;
}

